test_that("LOO MR returns one row per locus and handles one-locus edge case", {
  res <- make_fake_qtl2mr_analysis_result()
  loo <- loo_multilocus_founder_mr(res$pilot$fit)
  expect_s3_class(loo, "qtl2mr_loo_mr")
  expect_equal(nrow(loo), length(res$pilot$locus_blocks))
  expect_true(all(c("theta_minus_m", "delta_theta", "influence_rank") %in% names(loo)))
  expect_true(any(loo$status == "ok"))

  one_fit <- fit_multilocus_founder_mr(res$pilot$locus_blocks[1], compute_independence = FALSE)
  one <- loo_multilocus_founder_mr(one_fit)
  expect_equal(one$status, "single_locus_no_refit")
  expect_true(is.na(one$theta_minus_m))
})

