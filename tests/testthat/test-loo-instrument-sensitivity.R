test_that("instrument-set sensitivity refits named subsets", {
  res <- make_fake_qtl2mr_analysis_result()
  sets <- list(all = names(res$pilot$locus_blocks), first = names(res$pilot$locus_blocks)[1])
  sens <- fit_instrument_set_sensitivity(res, sets = sets)
  expect_s3_class(sens, "qtl2mr_instrument_sensitivity")
  expect_equal(nrow(sens), 2)
  expect_true(all(c("set_name", "n_loci", "theta", "profile_ci_lower", "profile_ci_upper") %in% names(sens)))
  expect_error(refit_qtl2mr_subset(res, subset = character()), "at least one marker")
  expect_error(refit_qtl2mr_subset(res, subset = "missing"), "not found")
})

test_that("LOO, sensitivity, and large-M plots render", {
  res <- make_fake_qtl2mr_analysis_result()
  loo <- loo_multilocus_founder_mr(res$pilot$fit)
  sens <- fit_instrument_set_sensitivity(res, sets = list(all = names(res$pilot$locus_blocks)))
  png1 <- tempfile(fileext = ".png")
  png2 <- tempfile(fileext = ".png")
  png3 <- tempfile(fileext = ".png")
  grDevices::png(png1)
  plot_loo_multilocus_mr(loo, top_n = 1)
  grDevices::dev.off()
  grDevices::png(png2)
  sens$set_name <- "exclude_top5_loo_influence"
  original_margins <- graphics::par("mai")
  plotted <- plot_instrument_set_sensitivity(sens, global_theta = res$pilot$summary$theta)
  expect_identical(plotted$set_name, sens$set_name)
  expect_equal(graphics::par("mai"), original_margins)
  grDevices::dev.off()
  grDevices::png(png3)
  plot_per_locus_so_forest(res$pilot$diagnostic_layer$per_locus, top_n = 1, order_by = "F")
  grDevices::dev.off()
  expect_true(file.exists(png1) && file.info(png1)$size > 0)
  expect_true(file.exists(png2) && file.info(png2)$size > 0)
  expect_true(file.exists(png3) && file.info(png3)$size > 0)
})
